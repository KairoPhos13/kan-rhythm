-- Users and OAuth tokens.
-- Table names borrow from the long-term design in server/migrations/0003_identity.sql
-- where that fits; this MVP schema is standalone.

CREATE TABLE users (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      text        NOT NULL,
    username_lower text GENERATED ALWAYS AS (lower(username)) STORED,
    email         text        NOT NULL,
    email_lower   text GENERATED ALWAYS AS (lower(email)) STORED,
    password_hash text        NOT NULL,
    country_code  char(2)     NOT NULL DEFAULT 'XX',
    join_date     timestamptz NOT NULL DEFAULT now(),
    last_visit    timestamptz,
    title         text        NOT NULL DEFAULT '',
    is_supporter  boolean     NOT NULL DEFAULT false,
    -- Media URLs stay empty in the MVP (see server/docs/lazer-protocol.md §8.3).
    avatar_url    text        NOT NULL DEFAULT '',
    cover_url     text        NOT NULL DEFAULT ''
);

CREATE UNIQUE INDEX users_username_lower_key ON users (username_lower);
CREATE UNIQUE INDEX users_email_lower_key    ON users (email_lower);

-- Opaque random tokens are stored hashed (SHA-256 hex); the plaintext exists
-- only in the client. Refresh tokens are rotated on use.
CREATE TABLE oauth_tokens (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             integer      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    access_token_hash   text         NOT NULL UNIQUE,
    refresh_token_hash  text         NOT NULL UNIQUE,
    access_expires_at   timestamptz  NOT NULL,
    refresh_expires_at  timestamptz  NOT NULL,
    created_at          timestamptz  NOT NULL DEFAULT now()
);

CREATE INDEX oauth_tokens_user_idx ON oauth_tokens (user_id);
CREATE INDEX oauth_tokens_refresh_expiry_idx ON oauth_tokens (refresh_expires_at);
