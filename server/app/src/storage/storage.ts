/**
 * File storage abstraction for level archives and covers.
 *
 * Two drivers (server/docs/mvp-scope.md §6):
 *  - `local`: files under a local directory (dev, tests) — downloads stream
 *    from disk;
 *  - `s3`: any S3-compatible store (Cloudflare R2, AWS S3) — downloads are
 *    answered with a 302 to a short-lived presigned URL.
 */
import { Readable } from 'node:stream';

export interface OpenedFile {
  stream: Readable;
  size: number;
}

export interface Storage {
  /** Uploads (or replaces) an object. */
  put(key: string, body: Buffer, contentType: string): Promise<void>;
  /** Removes an object; missing objects are not an error. */
  remove(key: string): Promise<void>;
  /**
   * Short-lived download URL to redirect to, or `null` when the driver serves
   * the bytes itself (see {@link open}).
   */
  presign(key: string, expiresInSeconds: number): Promise<string | null>;
  /** Opens a read stream for drivers that serve bytes themselves. */
  open(key: string): Promise<OpenedFile | null>;
  /** Whether the object exists. */
  exists(key: string): Promise<boolean>;
}

export const STORAGE = 'STORAGE';

/** Storage keys are generated by the server; keep them traversal-free anyway. */
export function isSafeKey(key: string): boolean {
  return key.length > 0 && !key.includes('..') && !key.startsWith('/') && !key.includes('\\');
}
