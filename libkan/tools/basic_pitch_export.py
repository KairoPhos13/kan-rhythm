#!/usr/bin/env python3
"""Export Basic Pitch weights into libkan (dev tool, not built).

Basic Pitch (Spotify, Apache-2.0, https://github.com/spotify/basic-pitch)
ships its ICASSP 2022 model as `basic_pitch/saved_models/icassp_2022/
nmp.onnx`. libkan runs that network in plain C++ (src/basic_pitch.cpp);
this script copies the constants out of the ONNX graph into
src/basic_pitch_weights.inc as exact hex-float literals.

Usage (needs the `onnx` and `numpy` packages):
    basic_pitch_export.py <nmp.onnx> <out.inc>

The graph layout is checked, not assumed: the script fails if the
constants it expects are missing or have another shape.
"""
import hashlib
import re
import sys

import numpy as np
import onnx
from onnx import numpy_helper

EXPECTED_SHA256 = "2c3c1d144bfa61ad236e92e169c13535c880469a12a047d4e73451f2c059a0ec"


def main() -> None:
    src, dst = sys.argv[1], sys.argv[2]
    blob = open(src, "rb").read()
    digest = hashlib.sha256(blob).hexdigest()
    if digest != EXPECTED_SHA256:
        sys.exit(f"unexpected model (sha256 {digest}); update the C++ port first")

    graph = onnx.load_from_string(blob).graph
    inits = {i.name: numpy_helper.to_array(i) for i in graph.initializer}

    # Convolutions in graph order: CQT (real/imag per octave + low-pass),
    # then the six network convolutions.
    convs = []
    for node in graph.node:
        if node.op_type != "Conv":
            continue
        attrs = {a.name: onnx.helper.get_attribute_value(a) for a in node.attribute}
        convs.append((inits[node.input[1]], inits[node.input[2]], attrs))

    # The imaginary CQT kernels are the ones whose output is negated.
    negated = set()
    for node in graph.node:
        if node.op_type == "Neg":
            negated.add(node.input[0])
    cqt_real = cqt_imag = None
    for node in graph.node:
        if node.op_type == "Conv" and inits[node.input[1]].shape == (36, 1, 1, 256):
            w = inits[node.input[1]]
            if node.output[0] in negated:
                cqt_imag = w
            else:
                cqt_real = w
    lowpass = next(w for w, _, _ in convs if w.shape == (1, 1, 1, 256))
    sqrt_len = next(v for v in inits.values() if v.shape == (309, 1, 1))

    # The input batch norm, folded to x * scale + shift (a Mul then an Add).
    def scalar_input(node):
        return next((inits[i] for i in node.input if i in inits and inits[i].shape == (1,)), None)

    bn_mul = next(n for n in graph.node if n.op_type == "Mul" and "batch_normalization" in n.output[0])
    bn_add = next(n for n in graph.node if n.op_type == "Add" and bn_mul.output[0] in n.input)
    bn_scale, bn_shift = scalar_input(bn_mul), scalar_input(bn_add)
    if bn_scale is None or bn_shift is None:
        sys.exit("expected the input batch norm as one scale and one shift")

    net = [c for c in convs if c[0].shape[2:] != (1, 256)]
    shapes = [c[0].shape for c in net]
    expected = [(32, 8, 5, 5), (8, 8, 3, 39), (1, 8, 5, 5), (32, 1, 7, 7), (1, 32, 7, 3), (1, 33, 3, 3)]
    if shapes != expected:
        sys.exit(f"unexpected network convolutions {shapes}")
    names = ["onset1", "contour1", "contour2", "note1", "note2", "onset2"]

    out = []
    out.append("// Generated by libkan/tools/basic_pitch_export.py from Basic Pitch")
    out.append("// (Spotify AB, Apache-2.0) saved_models/icassp_2022/nmp.onnx,")
    out.append(f"// sha256 {digest}. Do not edit by hand.")
    out.append("// clang-format off")

    def lit(x: float) -> str:
        # Shortest exact hex-float: a float32 needs at most 6 hex digits.
        return re.sub(r"\.?0+p", "p", float(x).hex()) + "f"

    def arr(name: str, a: np.ndarray) -> None:
        flat = np.asarray(a, dtype=np.float32).ravel()
        out.append(f"static const float {name}[{flat.size}] = {{")
        for i in range(0, flat.size, 6):
            out.append("    " + ", ".join(lit(x) for x in flat[i:i + 6]) + ",")
        out.append("};")

    arr("kCqtReal", cqt_real)
    arr("kCqtImag", cqt_imag)
    arr("kLowpass", lowpass)
    arr("kSqrtLengths", sqrt_len)
    out.append(f"static constexpr float kInputBnScale = {lit(bn_scale[0])};")
    out.append(f"static constexpr float kInputBnShift = {lit(bn_shift[0])};")
    for name, (w, b, attrs) in zip(names, net):
        arr(f"k_{name}_w", w)
        arr(f"k_{name}_b", b)
        out.append(f"// {name}: kernel {list(w.shape)}, strides {attrs['strides']}, pads {attrs['pads']}")
    out.append("// clang-format on")
    open(dst, "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
