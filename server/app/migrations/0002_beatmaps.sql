-- Beatmapsets and beatmaps (levels imported from .osz archives).
-- `checksum` is the MD5 of the *rewritten* .osu file as served in the archive:
-- it is what the client looks up and later sends as `beatmap_hash`.

CREATE TABLE beatmapsets (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        integer REFERENCES users (id) ON DELETE SET NULL,
    title          text           NOT NULL DEFAULT '',
    title_unicode  text           NOT NULL DEFAULT '',
    artist         text           NOT NULL DEFAULT '',
    artist_unicode text           NOT NULL DEFAULT '',
    creator        text           NOT NULL DEFAULT '',
    source         text           NOT NULL DEFAULT '',
    tags           text           NOT NULL DEFAULT '',
    -- BeatmapOnlineStatus (lazer-protocol.md §7): 1 = ranked. Kept as a column
    -- so a review workflow can come later.
    status         smallint       NOT NULL DEFAULT 1,
    bpm            double precision NOT NULL DEFAULT 0,
    genre_id       integer        NOT NULL DEFAULT 1,
    language_id    integer        NOT NULL DEFAULT 1,
    nsfw           boolean        NOT NULL DEFAULT false,
    video          boolean        NOT NULL DEFAULT false,
    storyboard     boolean        NOT NULL DEFAULT false,
    play_count     integer        NOT NULL DEFAULT 0,
    favourite_count integer       NOT NULL DEFAULT 0,
    submitted_date timestamptz    NOT NULL DEFAULT now(),
    ranked_date    timestamptz,
    last_updated   timestamptz    NOT NULL DEFAULT now(),
    archive_key    text           NOT NULL,
    cover_key      text
);

CREATE INDEX beatmapsets_user_idx   ON beatmapsets (user_id);
CREATE INDEX beatmapsets_status_idx ON beatmapsets (status, ranked_date DESC);
CREATE INDEX beatmapsets_title_idx  ON beatmapsets (lower(title));
CREATE INDEX beatmapsets_artist_idx ON beatmapsets (lower(artist));

CREATE TABLE beatmaps (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    beatmapset_id     integer         NOT NULL REFERENCES beatmapsets (id) ON DELETE CASCADE,
    version           text            NOT NULL DEFAULT '',
    filename          text            NOT NULL DEFAULT '',
    checksum          text            NOT NULL,
    -- mode_int is what the client reads; it must stay within 0-3
    -- (lazer-protocol.md §4.6).
    mode_int          smallint        NOT NULL DEFAULT 0,
    difficulty_rating double precision NOT NULL DEFAULT 0,
    cs                real            NOT NULL DEFAULT 0,
    ar                real            NOT NULL DEFAULT 0,
    accuracy          real            NOT NULL DEFAULT 0,
    drain             real            NOT NULL DEFAULT 0,
    total_length      integer         NOT NULL DEFAULT 0,
    hit_length        integer         NOT NULL DEFAULT 0,
    max_combo         integer         NOT NULL DEFAULT 0,
    bpm               double precision NOT NULL DEFAULT 0,
    count_circles     integer         NOT NULL DEFAULT 0,
    count_sliders     integer         NOT NULL DEFAULT 0,
    count_spinners    integer         NOT NULL DEFAULT 0,
    last_updated      timestamptz     NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX beatmaps_checksum_key ON beatmaps (checksum);
CREATE INDEX beatmaps_set_idx ON beatmaps (beatmapset_id);
CREATE INDEX beatmaps_filename_idx ON beatmaps (lower(filename));
