-- Score tokens (one per play) and submitted scores.
-- Ruleset is stored as data (ruleset_id + ruleset_short_name) instead of being
-- hard-coded: kan! reports ruleset_id 0 on the wire (lazer-protocol.md §8.1).

CREATE TABLE score_tokens (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            integer      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    beatmap_id         integer      NOT NULL REFERENCES beatmaps (id) ON DELETE CASCADE,
    beatmap_hash       text         NOT NULL,
    ruleset_id         integer      NOT NULL DEFAULT 0,
    ruleset_short_name text         NOT NULL DEFAULT 'kan',
    version_hash       text         NOT NULL DEFAULT '',
    created_at         timestamptz  NOT NULL DEFAULT now(),
    expires_at         timestamptz  NOT NULL,
    used_at            timestamptz
);

CREATE INDEX score_tokens_user_idx    ON score_tokens (user_id);
CREATE INDEX score_tokens_expiry_idx  ON score_tokens (expires_at);

CREATE TABLE scores (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 integer         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    beatmap_id              integer         NOT NULL REFERENCES beatmaps (id) ON DELETE CASCADE,
    ruleset_id              integer         NOT NULL DEFAULT 0,
    ruleset_short_name      text            NOT NULL DEFAULT 'kan',
    score_token_id          bigint REFERENCES score_tokens (id) ON DELETE SET NULL,
    total_score             bigint          NOT NULL DEFAULT 0,
    total_score_without_mods bigint         NOT NULL DEFAULT 0,
    accuracy                double precision NOT NULL DEFAULT 0,
    max_combo               integer         NOT NULL DEFAULT 0,
    rank                    text            NOT NULL DEFAULT 'D',
    passed                  boolean         NOT NULL DEFAULT true,
    mods                    jsonb           NOT NULL DEFAULT '[]'::jsonb,
    statistics              jsonb           NOT NULL DEFAULT '{}'::jsonb,
    maximum_statistics      jsonb           NOT NULL DEFAULT '{}'::jsonb,
    pauses                  jsonb           NOT NULL DEFAULT '[]'::jsonb,
    build_id                integer,
    started_at              timestamptz,
    ended_at                timestamptz     NOT NULL DEFAULT now(),
    created_at              timestamptz     NOT NULL DEFAULT now()
);

CREATE INDEX scores_beatmap_idx ON scores (beatmap_id, ruleset_short_name, total_score DESC);
CREATE INDEX scores_user_idx    ON scores (user_id, ended_at DESC);
